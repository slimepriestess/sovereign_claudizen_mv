"""force_align.py: per-word lyric times by forced alignment (torchaudio MMS_FA) of the whole lyric sheet against the demucs
vocal stem, in one pass (Suno sang the sheet exactly, in order; whisper is blind to the shouted "Heave ho!"s, so it can't
anchor sections). Words the aligner can't spell as sung get a pronunciation (SAY). -> src/lyrtimes.js
Run: ../the_valley_mv/.venv/bin/python analysis/force_align.py"""
import json, re, unicodedata, torch, librosa
from torchaudio.pipelines import MMS_FA as bundle
model = bundle.get_model(); tok = bundle.get_tokenizer(); aligner = bundle.get_aligner()
y = librosa.load('analysis/stems/htdemucs/track/vocals.wav', sr=16000, mono=True)[0]; wav = torch.from_numpy(y).unsqueeze(0)
SAY = {'vlookups': 'veelookups', 'r-l-h-f,': 'arelaitcheff', 'claude': 'clawd', "claude's": 'clawds'}
norm = lambda w: re.sub(r"[^a-z]", '', unicodedata.normalize('NFKD', w.lower().replace('’', "'")).encode('ascii', 'ignore').decode())
secs, cur = [], None
for raw in open('notes/LYRICS.txt').read().splitlines():
    raw = raw.strip()
    if not raw: continue
    m = re.match(r'\[(.+)\]', raw)
    if m: cur = {'sec': m.group(1), 'lines': []}; secs.append(cur); continue
    cur['lines'].append({'text': raw, 'words': raw.split()})
flat = [(si, li, wi, w) for si, s in enumerate(secs) for li, l in enumerate(s['lines']) for wi, w in enumerate(l['words'])]
spoken = [(x, norm(SAY.get(x[3].lower().strip('"!?.,—'), SAY.get(x[3].lower(), x[3])))) for x in flat]
spoken = [(x, s) for x, s in spoken if s]
with torch.inference_mode(): em, _ = model(wav)
spans = aligner(em[0], tok([s for _, s in spoken]))
ratio = wav.shape[1] / em.shape[1] / 16000
T = {}
for (x, _), sp in zip(spoken, spans): T[x[:3]] = (round(sp[0].start * ratio, 2), round(sp[-1].end * ratio, 2))
out = []
for si, s in enumerate(secs):
    L = []
    for li, l in enumerate(s['lines']):
        ws = [[w, *T.get((si, li, wi), (None, None))] for wi, w in enumerate(l['words'])]
        for k, w in enumerate(ws):                           # a word with no letters (a dash) takes its neighbour's time
            if w[1] is None: w[1] = w[2] = (ws[k - 1][2] if k else ws[k + 1][1])
        L.append({'text': l['text'], 't0': ws[0][1], 't1': ws[-1][2], 'words': [[w, a] for w, a, _ in ws]})
    out.append({'sec': s['sec'], 't0': L[0]['t0'], 't1': L[-1]['t1'], 'lines': L})
open('src/lyrtimes.js', 'w').write('// generated by analysis/force_align.py: sections > lines > [[word, start s]] (MMS forced alignment on the vocal stem)\nconst LYRT = ' + json.dumps(out, ensure_ascii=False) + ';\n')
for s in out:
    print(f"{s['t0']:7.2f}-{s['t1']:7.2f}  [{s['sec']}]")
    for l in s['lines']: print(f"   {l['t0']:7.2f}-{l['t1']:7.2f}  {l['text'][:70]}")
